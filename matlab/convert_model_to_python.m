csvwrite('W2.csv', weights_biases.W2);
csvwrite('b2.csv', weights_biases.b2);
csvwrite('W3.csv', weights_biases.W3);
csvwrite('b3.csv', weights_biases.b3);
csvwrite('input_min.csv', weights_biases.input_min);
csvwrite('input_max.csv', weights_biases.input_max);
csvwrite('output_min.csv', weights_biases.output_min);
csvwrite('output_max.csv', weights_biases.output_max);

fprintf('✓ Individual weight matrices saved as CSV files\n');

%% ===== CREATE PYTHON INFERENCE SCRIPT =====
python_code = ['import numpy as np' newline ...
'import json' newline ...
newline ...
'class LegIKModel:' newline ...
