%% Convert MATLAB Neural Network Model to Python Format
% Description: Exports trained model weights and parameters for use in Python/NumPy

clear all; close all; clc;

fprintf('===== Converting Model to Python Format =====\n\n');

%% ===== LOAD TRAINED MODEL =====
load('model_weights.mat');

fprintf('✓ Model weights loaded\n\n');

%% ===== CREATE PYTHON-COMPATIBLE JSON FILE =====
% Create structure for JSON export
python_model = struct();

% Network architecture
python_model.architecture = struct();
python_model.architecture.input_size = 3;
python_model.architecture.hidden1_size = size(weights_biases.W1, 1);
python_model.architecture.hidden2_size = size(weights_biases.W2, 1);
python_model.architecture.output_size = 3;

% Weights and biases (convert to lists for JSON)
python_model.weights = struct();
python_model.weights.W1 = weights_biases.W1;
python_model.weights.b1 = reshape(weights_biases.b1, [], 1);
python_model.weights.W2 = weights_biases.W2;
python_model.weights.b2 = reshape(weights_biases.b2, [], 1);
python_model.weights.W3 = weights_biases.W3;
python_model.weights.b3 = reshape(weights_biases.b3, [], 1);

% Normalization parameters
python_model.normalization = struct();
python_model.normalization.input_min = reshape(weights_biases.input_min, [], 1);
python_model.normalization.input_max = reshape(weights_biases.input_max, [], 1);
python_model.normalization.output_min = reshape(weights_biases.output_min, [], 1);
python_model.normalization.output_max = reshape(weights_biases.output_max, [], 1);

% Save as JSON
json_str = jsonencode(python_model);
fid = fopen('model_for_python.json', 'w');
fprintf(fid, '%s', json_str);
fclose(fid);

fprintf('✓ Model exported to JSON: model_for_python.json\n');

%% ===== ALSO SAVE AS SIMPLE TEXT FORMAT =====
% Save weights as CSV for easy loading in Python
csvwrite('W1.csv', weights_biases.W1);
